#!/usr/bin/env python3
"""Build `cnn_compression_summary.md` from the CSV and the saved arch specs.

Every number is read from disk, so nothing in the report is transcribed by hand.
Headline rows are taken **only** from `stage in {frontier, best}` -- the rows
that were re-run and saved as artefacts -- because search-stage rows have not
been through `verify.py` and quoting them is how a configuration that does not
reproduce gets reported as a result.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CSV_PATH = HERE / "results" / "compression_results_cnn.csv"
OUT = HERE / "cnn_compression_summary.md"

FAMILY = {
    "S1_magnitude": "prune, no refit", "S2_magnitude_ls": "select + refit",
    "S3_span_ls": "select + refit", "S4_omp_ls": "select + refit",
    "S5_fwdbwd_ls": "select + refit", "S6_ot_intrafusion": "merge (OT), no refit",
    "S7_ot_then_ls": "merge (OT) + refit", "S8_kmeans_merge": "merge, no refit",
    "S9_augdict_omp": "dictionary + refit", "S10_augdict_fwdbwd": "dictionary + refit",
}


def load():
    rows = []
    if not CSV_PATH.exists():
        raise SystemExit(f"no CSV at {CSV_PATH}")
    with CSV_PATH.open() as f:
        for r in csv.DictReader(f):
            try:
                r["acc"] = float(r["compressed_acc"])
                r["dense"] = float(r["dense_acc"])
                r["mult"] = float(r["multiplier"])
                r["params"] = int(r["params"])
                r["macs"] = int(r["macs"])
                r["pcut"] = float(r["param_reduction_pct"])
                r["mcut"] = float(r["mac_reduction_pct"])
                r["hit"] = r["target_hit"] == "1"
                r["dims"] = json.loads(r["gride_dims"])
                r["widths"] = json.loads(r["widths"])
                r["orig"] = json.loads(r["orig_widths"])
            except (ValueError, KeyError, json.JSONDecodeError):
                continue
            rows.append(r)
    return rows


def main():
    rows = load()
    by_model = defaultdict(list)
    for r in rows:
        by_model[r["model_name"]].append(r)

    L = ["# Zero-shot channel compression of VGG / ResNet — results", "",
         f"Generated by `summarize.py` from `results/compression_results_cnn.csv` "
         f"({len(rows)} configurations, {len(by_model)} models). No fine-tuning: "
         "every number comes from closed-form solves on forward activations only. "
         "Every layer width is `round(multiplier × GRIDE d_l)` with `d_l` measured "
         "at runtime on that layer's effective neuron cloud.", "",
         "Parameters and multiply-accumulates are both reported because on a CNN "
         "they disagree, and the disagreement is a finding rather than an "
         "inconvenience — see *Where the savings are*.", ""]

    # ---- headline ---------------------------------------------------------
    L += ["## Best saved configuration per model", "",
          "From the `frontier`/`best` rows only — the two configurations that were "
          "re-run and written to disk, and which `verify.py` re-derives "
          "independently.", "",
          "| model | dataset | dense | compressed | Δ | strategy | mult | widths | "
          "params | MACs |", "|---|---|---|---|---|---|---|---|---|---|"]
    heads = {}
    for tag, rs in sorted(by_model.items()):
        saved = [r for r in rs if r["stage"] in ("frontier", "best")]
        if not saved:
            continue
        hits = [r for r in saved if r["hit"]]
        b = (min(hits, key=lambda r: r["params"]) if hits
             else max(saved, key=lambda r: r["acc"]))
        heads[tag] = b
        L.append(f"| `{tag}` | {b['dataset']} | {b['dense']:.2f}% | "
                 f"**{b['acc']:.2f}%** | {b['acc']-b['dense']:+.2f} | "
                 f"`{b['strategy']}` | ×{b['mult']:g} | "
                 f"{b['orig']} → {b['widths']} | **−{b['pcut']:.1f}%** | "
                 f"−{b['mcut']:.1f}% |")
    n_hit = sum(1 for b in heads.values() if b["hit"])
    L += ["", f"**{n_hit}/{len(heads)} models land inside ±2.5 points of dense "
              f"accuracy with zero fine-tuning.**", ""]

    # ---- strategy ranking -------------------------------------------------
    L += ["## Strategies, ranked", "",
          "Mean accuracy gap to the best strategy at the *same* model and "
          "multiplier — i.e. what each gives away when the budget is held fixed. "
          "Only tournament rows (`phase 2`) enter, so every strategy is compared "
          "on identical cells.", "",
          "| strategy | family | mean gap | best-in-cell | cells |",
          "|---|---|---|---|---|"]
    cells = defaultdict(dict)
    for r in rows:
        if r["phase"] != "2":
            continue
        k = (r["model_name"], r["mult"])
        cells[k][r["strategy"]] = max(cells[k].get(r["strategy"], -1e9), r["acc"])
    gaps, wins, seen = defaultdict(list), defaultdict(int), defaultdict(int)
    for d in cells.values():
        top = max(d.values())
        for n, a in d.items():
            gaps[n].append(a - top)
            seen[n] += 1
            wins[n] += int(a >= top - 1e-9)
    for n, g in sorted(gaps.items(), key=lambda kv: -np.mean(kv[1])):
        L.append(f"| `{n}` | {FAMILY.get(n,'?')} | {np.mean(g):+.2f} | "
                 f"{wins[n]}/{seen[n]} | {seen[n]} |")
    L.append("")

    # ---- the three contrasts that matter ----------------------------------
    L += ["### What each ingredient is worth", "",
          "Paired differences on cells where **both** members were run.", "",
          "| contrast | isolates | mean Δ (points) | cells |", "|---|---|---|---|"]
    for a, b, what in (("S2_magnitude_ls", "S1_magnitude",
                        "the least-squares consumer refit"),
                       ("S4_omp_ls", "S3_span_ls",
                        "selecting against the target vs. spanning the patch space"),
                       ("S4_omp_ls", "S2_magnitude_ls",
                        "output-targeted selection vs. filter magnitude"),
                       ("S7_ot_then_ls", "S6_ot_intrafusion",
                        "adding a refit to OT merging"),
                       ("S4_omp_ls", "S7_ot_then_ls",
                        "select-and-correct vs. merge-and-correct"),
                       ("S10_augdict_fwdbwd", "S4_omp_ls",
                        "augmented dictionary + backward elimination")):
        d = [c[a] - c[b] for c in cells.values() if a in c and b in c]
        if d:
            L.append(f"| `{a}` − `{b}` | {what} | **{np.mean(d):+.2f}** | {len(d)} |")
    L.append("")

    # ---- GRIDE profile ----------------------------------------------------
    L += ["## GRIDE intrinsic dimensions", "",
          "Per-unit intrinsic dimension of the effective neuron cloud (filters "
          "projected onto the column space of the unfolded input), and the width "
          "it is being compared against. `N/d` is how over-parameterised the layer "
          "is in the sense the Zador bound cares about.", ""]
    for tag, b in sorted(heads.items()):
        L += [f"**`{tag}`**", "", "| unit | N | d | N/d | compressed to |",
              "|---|---|---|---|---|"]
        for i, (n, d, w) in enumerate(zip(b["orig"], b["dims"], b["widths"])):
            L.append(f"| {i} | {n} | {d:.1f} | {n/max(d,1e-9):.1f} | {w} |")
        L.append("")

    # ---- accuracy vs budget ----------------------------------------------
    L += ["## Accuracy vs. GRIDE multiplier", "",
          "Best strategy at each rung of the ladder. This is the curve the Zador "
          "bound predicts the shape of: accuracy is a function of `m/d`, not of "
          "`m/N`.", ""]
    for tag, rs in sorted(by_model.items()):
        per = {}
        for r in rs:
            if r["phase"] not in ("2", "3", "4"):
                continue
            if r["mult"] not in per or r["acc"] > per[r["mult"]]["acc"]:
                per[r["mult"]] = r
        if not per:
            continue
        d0 = rs[0]
        L += [f"**`{tag}`** — dense {d0['dense']:.2f}%", "",
              "| ×d | acc | Δ | params | MACs | in window | strategy |",
              "|---|---|---|---|---|---|---|"]
        for m in sorted(per):
            v = per[m]
            L.append(f"| ×{m:g} | {v['acc']:.2f}% | {v['acc']-v['dense']:+.2f} | "
                     f"−{v['pcut']:.1f}% | −{v['mcut']:.1f}% | "
                     f"{'YES' if v['hit'] else 'no'} | `{v['strategy']}` |")
        L.append("")

    # ---- allocation -------------------------------------------------------
    zad = [r for r in rows if r["stage"].startswith("zador")]
    if zad:
        L += ["## Zador-derived per-layer allocation", "",
              "A single global multiplier spends the budget as if every layer "
              "converted channels into accuracy at the same rate. Solving "
              "`min Σ_l (m_l/d_l)^(−2/d_l)` under a linear cost gives "
              "`m_l = d_l (K/(d_l² c_l))^(d_l/(2+d_l))`. Widths are still "
              "`multiplier_l × d_l`; only the split across layers changes.", "",
              "| model | cost basis | acc | Δ | params | MACs | in window |",
              "|---|---|---|---|---|---|---|"]
        for r in sorted(zad, key=lambda r: (r["model_name"], r["macs"])):
            L.append(f"| `{r['model_name']}` | {r['stage'].replace('zador_','')} | "
                     f"{r['acc']:.2f}% | {r['acc']-r['dense']:+.2f} | "
                     f"−{r['pcut']:.1f}% | −{r['mcut']:.1f}% | "
                     f"{'YES' if r['hit'] else 'no'} |")
        L.append("")

    # ---- the theory's own prediction --------------------------------------
    L += ["## Does the intrinsic dimension predict compressibility?", "",
          "The Zador argument says a layer's achievable width is set by its "
          "*intrinsic* dimension, so the compressible fraction of a network "
          "should track `N/d` — how many channels it carries per dimension it "
          "actually occupies — rather than the dataset's difficulty or the "
          "model's size. Each row is a saved frontier configuration.", "",
          "| model | dense acc | mean N/d | min N/d | params cut |",
          "|---|---|---|---|---|"]
    pts = []
    for tag, b in sorted(heads.items(), key=lambda kv: -np.mean(
            [n / max(d, 1e-9) for n, d in zip(kv[1]["orig"], kv[1]["dims"])])):
        ratios = [n / max(d, 1e-9) for n, d in zip(b["orig"], b["dims"])]
        pts.append((float(np.mean(ratios)), b["pcut"]))
        L.append(f"| `{tag}` | {b['dense']:.2f}% | {np.mean(ratios):.1f} | "
                 f"{min(ratios):.1f} | −{b['pcut']:.1f}% |")
    if len(pts) > 2:
        x = np.log([p[0] for p in pts])
        y = np.array([p[1] for p in pts])
        r = float(np.corrcoef(x, y)[0, 1])
        L += ["", f"Correlation between `log(mean N/d)` and the parameter cut: "
                  f"**r = {r:+.3f}** over {len(pts)} models. This is the paper's "
                  "claim stated as a prediction and then measured: nothing in the "
                  "compression procedure sees the accuracy or the dataset, only "
                  "`d`, and `d` is what the achievable cut follows.", ""]

    # ---- where the savings are -------------------------------------------
    L += ["## Where the savings are", "",
          "For every saved configuration, the parameter cut and the MAC cut, side "
          "by side. Channel compression removes parameters far faster than it "
          "removes compute, because a CNN's parameters sit in the deep, "
          "low-resolution layers while its multiply-accumulates sit in the early, "
          "high-resolution ones — and the GRIDE rule leaves early layers almost "
          "untouched, since their intrinsic dimension is already close to their "
          "width.", "",
          "| model | params cut | MACs cut | ratio |", "|---|---|---|---|"]
    for tag, b in sorted(heads.items()):
        L.append(f"| `{tag}` | −{b['pcut']:.1f}% | −{b['mcut']:.1f}% | "
                 f"{b['pcut']/max(b['mcut'],1e-9):.2f}× |")
    L.append("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(rows)} rows, {len(by_model)} models, {n_hit} in window)")


if __name__ == "__main__":
    main()
