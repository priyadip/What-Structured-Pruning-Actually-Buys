#!/usr/bin/env python3
"""Build the cross-model results document from results/compression_results.csv.

Writes `notes/02_results.md`. Regenerate any time after a sweep -- everything is
read from the CSV and the run logs, so nothing is transcribed by hand.
"""

from __future__ import annotations

import csv
import json
import re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSV_PATH = HERE / "results" / "compression_results.csv"
OUT = HERE / "notes" / "02_results.md"
TOL = 2.5

# Which family each strategy belongs to. The split that matters is whether the
# consuming layer is rebuilt by the corrected least-squares solve or not.
LS_SEED = {"01_direct_ls_svd", "07_mixed_importance", "08_ot_then_ls",
           "10_iterative_refinement"}
MERGE = {"03_activation_pattern_kmeans", "05_balanced_signature",
         "06_greedy_wasserstein1", "09_kernel_kmeans_rbf"}
PRUNE = {"02_topm_l2_norm", "04_cosine_ot_intrafusion"}


def family(name: str) -> str:
    if name.startswith("N"):
        return "LS-corrected (novel)"
    if name in LS_SEED:
        return "LS-corrected (seed)"
    if name in MERGE:
        return "merging"
    if name in PRUNE:
        return "prune / OT-transport"
    return "other"


def load() -> list[dict]:
    with CSV_PATH.open() as f:
        rows = list(csv.DictReader(f))
    out = []
    for r in rows:
        try:
            r["acc"] = float(r["compressed_acc"])
            r["dense"] = float(r["original_acc"])
            r["drop"] = float(r["acc_drop"])
            r["red"] = float(r["param_reduction_pct"])
            r["params"] = int(r["params"])
            r["mult"] = float(r["multiplier"])
        except (ValueError, KeyError):
            continue                 # per-layer-allocation rows: multiplier is a list
        out.append(r)
    return out


def frontiers() -> dict[str, str]:
    """Pull the phase-4 frontier line out of each run log."""
    out = {}
    for log in (HERE / "results").glob("final_*.log"):
        txt = log.read_text(errors="ignore")
        m = re.search(r"frontier: smallest GRIDE budget inside the window is "
                      r"x([\d.]+) -> M=(\[[^\]]*\]) \(([\d,]+) params, -([\d.]+)%\)", txt)
        if m:
            out[log.stem.replace("final_", "")] = m.groups()
    return out


def main():
    rows = load()
    if not rows:
        raise SystemExit(f"no usable rows in {CSV_PATH}")
    fr = frontiers()

    by_model: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in rows:
        by_model[(r["dataset"], r["model_name"])].append(r)

    L = ["# Results — GRIDE-budgeted zero-shot compression", "",
         "Generated by `compression_mlp/summarize.py` from `results/compression_results.csv` "
         f"({len(rows)} runs, {len(by_model)} checkpoints). Target window is dense "
         f"accuracy ±{TOL} points. **No fine-tuning anywhere** — every number below "
         "comes from closed-form solves over unlabelled calibration inputs.", "",
         "Every width is `M_l = round(multiplier · d_l)` with `d_l` the GRIDE intrinsic "
         "dimension of layer *l*'s neuron cloud, measured at runtime.", ""]

    # ---------------- headline ---------------------------------------------
    L += ["## The compression frontier",
          "",
          "The smallest GRIDE budget that still lands inside the ±2.5 window, located "
          "by bisection (phase 4) rather than read off the coarse multiplier ladder.",
          "",
          "| dataset | model | dense | GRIDE d | widths | compressed | drop | params | **reduction** | mult |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for (ds, mn), rs in sorted(by_model.items()):
        hits = [r for r in rs if abs(r["drop"]) <= TOL]
        if not hits:
            L.append(f"| {ds} | `{mn}` | {rs[0]['dense']:.2f}% | — | — | *no hit* | | | | |")
            continue
        best = max(hits, key=lambda r: r["red"])
        d = json.loads(best["gride_dims"])
        L.append(f"| {ds} | `{mn}` | {best['dense']:.2f}% | {[round(x,1) for x in d]} | "
                 f"{json.loads(best['orig_widths'])} → {json.loads(best['widths'])} | "
                 f"**{best['acc']:.2f}%** | {-best['drop']:+.2f} | {best['params']:,} | "
                 f"**{best['red']:.1f}%** | x{best['mult']:g} |")
    L.append("")
    if fr:
        L += ["Phase-4 bisection endpoints (uniform multiplier, before the phase-3 "
              "allocation search trims further):", "",
              "| checkpoint | frontier multiplier | widths | params | reduction |",
              "|---|---|---|---|---|"]
        for k, (mult, w, pars, red) in sorted(fr.items()):
            L.append(f"| `{k}` | x{mult} | {w} | {pars} | {red}% |")
        L.append("")

    # ---------------- family comparison ------------------------------------
    L += ["## What actually separates the methods", "",
          "Best accuracy reached by each *family* at each GRIDE budget. The families are:",
          "",
          "- **LS-corrected** — the consuming layer is rebuilt by the closed-form "
          "least-squares solve with an intercept, against the dense network's target "
          "(seed strategies 01/07/08/10 and every `N*`).",
          "- **merging** — neurons are replaced by cluster barycentres "
          "(03/05/06/09).",
          "- **prune / OT-transport** — magnitude pruning (02) and the Intra-Fusion "
          "OT baseline (04).", ""]
    for (ds, mn), rs in sorted(by_model.items()):
        base = [r for r in rs if r["phase"] in ("1", "2")]
        if not base:
            continue
        grid: dict[float, dict[str, float]] = defaultdict(dict)
        for r in base:
            f = family(r["strategy_name"])
            grid[r["mult"]][f] = max(grid[r["mult"]].get(f, -1), r["acc"])
        L += [f"### {ds} / `{mn}` — dense {rs[0]['dense']:.2f}%, "
              f"GRIDE d = {[round(x,2) for x in json.loads(base[0]['gride_dims'])]}", "",
              "| multiplier | widths | reduction | LS-corrected | merging | prune/OT | "
              "LS advantage |", "|---|---|---|---|---|---|---|"]
        for m in sorted(grid):
            g = grid[m]
            ls = max([v for k, v in g.items() if k.startswith("LS")] or [float("nan")])
            mg = g.get("merging", float("nan"))
            pr = g.get("prune / OT-transport", float("nan"))
            other = max([x for x in (mg, pr) if x == x] or [float("nan")])
            ex = next(r for r in base if r["mult"] == m)
            L.append(f"| x{m:g} | {json.loads(ex['widths'])} | {ex['red']:.1f}% | "
                     f"**{ls:.2f}%** | {mg:.2f}% | {pr:.2f}% | +{ls-other:.2f} |")
        L.append("")

    # ---------------- per-strategy leaderboard -----------------------------
    L += ["## Per-strategy leaderboard", "",
          "Best each strategy reached on each checkpoint, at whatever budget suited it.", ""]
    for (ds, mn), rs in sorted(by_model.items()):
        best: dict[str, dict] = {}
        for r in rs:
            s = r["strategy_name"]
            if s not in best or r["acc"] > best[s]["acc"]:
                best[s] = r
        L += [f"**{ds} / `{mn}`**", "",
              "| strategy | family | best acc | mult | widths | reduction |",
              "|---|---|---|---|---|---|"]
        for k, v in sorted(best.items(), key=lambda kv: -kv[1]["acc"]):
            L.append(f"| `{k}` | {family(k)} | {v['acc']:.2f}% | x{v['mult']:g} | "
                     f"{json.loads(v['widths'])} | {v['red']:.1f}% |")
        L.append("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(rows)} runs, {len(by_model)} checkpoints)")


if __name__ == "__main__":
    main()
