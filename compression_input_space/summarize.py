#!/usr/bin/env python3
"""Build `input_compression_summary.md` from `results/input_compression_results.csv`.

Everything is read from the CSV and the compression_mlp/ arch specs, so no number in the
report is transcribed by hand. Regenerate after any sweep.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
PROJECT_ROOT = HERE.parent
CSV_PATH = HERE / "results" / "input_compression_results.csv"
EXPLORE = PROJECT_ROOT / "compression_mlp" / "results"
OUT = HERE / "input_compression_summary.md"

FAMILY_KIND = {
    "opt_linear": "linear ceiling (closed form)",
    "pca": "linear baseline",
    "w1_svd": "linear baseline",
    "random": "linear baseline",
    "srgw_gower": "srGW-MDS",
    "srgw_nystrom": "srGW-MDS",
    "srgw_relaxed": "srGW-MDS",
    "srgw_linear": "srGW-MDS (distilled linear)",
    "N1_jacobian_linear": "novel: logit-pullback metric",
    "N3_actfreq_linear": "novel: activation-frequency metric",
    "N2_rff1024": "novel: random Fourier features",
}


def dense_params(spec: dict) -> int:
    dims = [spec["in_dim"]] + list(spec["original_widths"]) + [spec["num_classes"]]
    return sum(dims[i] * dims[i + 1] + dims[i + 1] for i in range(len(dims) - 1))


def load():
    rows = []
    with CSV_PATH.open() as f:
        for r in csv.DictReader(f):
            try:
                r["acc"] = float(r["compressed_acc"])
                r["r"] = int(float(r["r"]))
                r["dense"] = float(r["dense_acc"])
                r["hidden"] = float(r["hidden_only_acc"])
                r["params"] = int(r["total_params"])
                r["cwf"] = float(r["cwf"])
                r["hit"] = r["target_hit"] == "1"
                r["folds"] = r["folds_into_layer1"] == "1"
                r["lam"] = float(r["lambda"])
                r["K"] = int(r["K"])
                r["d_in"] = float(r["r_input_gride"])
                r["flops"] = int(r["encoder_flops"])
            except (ValueError, KeyError):
                continue
            rows.append(r)
    return rows


def main():
    rows = load()
    if not rows:
        raise SystemExit(f"no usable rows in {CSV_PATH}")
    by_model = defaultdict(list)
    for r in rows:
        by_model[r["model_name"]].append(r)

    specs = {}
    for tag in by_model:
        p = EXPLORE / f"{tag}.arch.json"
        if p.exists():
            specs[tag] = json.loads(p.read_text())

    L = ["# Input reduction + first-layer refit — results", "",
         f"Generated by `summarize.py` from `results/input_compression_results.csv` "
         f"({len(rows)} runs, {len(by_model)} models). Hidden layers **frozen**; only the "
         "embedding and the linear map `A` are fitted. `r` is always "
         "`round(multiplier × GRIDE d_input)` measured on raw pixels at runtime.", "",
         "`Δ dense` is against the *original* uncompressed model; `Δ hidden` is against "
         "the hidden-compressed model this builds on — the latter is what input "
         "reduction itself costs.", ""]

    # ---- headline: best config per model ---------------------------------
    L += ["## Best configuration per model", "",
          "Taken **only from runs re-fitted on the full training set** (`stage` = "
          "`frontier`/`final`). Search-stage rows come from a 20 000-sample "
          "subsample and are systematically optimistic at the window boundary — "
          "quoting them is how a configuration that actually misses gets reported "
          "as a hit.", "",
          "| model | D → r | mult | d_input | encoder | dense | hidden-only | **full** | "
          "Δ dense | Δ hidden | params | vs dense params | CWF |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    best_per_model = {}
    for tag, rs in sorted(by_model.items()):
        # only configurations validated on the full training set may be quoted
        full = [r for r in rs if r["stage"] in ("frontier", "final")]
        hits = [r for r in full if r["hit"]]
        b = (min(hits, key=lambda r: (r["r"], -r["acc"])) if hits
             else max(full or rs, key=lambda r: r["acc"]))
        best_per_model[tag] = b
        sp = specs.get(tag)
        dp = dense_params(sp) if sp else 0
        red = f"−{100*(1-b['params']/dp):.1f}%" if dp else "—"
        L.append(f"| `{tag}` | {b['input_dim']} → **{b['r']}** | "
                 f"×{b['r']/b['d_in']:.2f} | {b['d_in']:.1f} | `{b['encoder_family']}` | "
                 f"{b['dense']:.2f}% | {b['hidden']:.2f}% | **{b['acc']:.2f}%** | "
                 f"{b['acc']-b['dense']:+.2f} | {b['acc']-b['hidden']:+.2f} | "
                 f"{b['params']:,} | {red} | {b['cwf']:.3f} |")
    n_hit = sum(1 for b in best_per_model.values() if b["hit"])
    L += ["", f"**{n_hit}/{len(best_per_model)} models land inside ±2.5 of the original "
              f"dense accuracy with both the hidden layers and the input compressed.**", ""]

    # ---- encoder family ranking ------------------------------------------
    L += ["## Encoder families, ranked", "",
          "Mean gap to the best encoder at the same (model, r) — i.e. how much each "
          "family gives away when the budget is held fixed. Lower is better.", "",
          "| encoder | kind | mean gap | best-in-cell | folds into layer 1 | cells |",
          "|---|---|---|---|---|---|"]
    cells = defaultdict(dict)
    for r in rows:
        k = (r["model_name"], r["r"])
        f = r["encoder_family"]
        if f not in cells[k] or r["acc"] > cells[k][f]["acc"]:
            cells[k][f] = r
    gaps, wins, folds, seen = defaultdict(list), defaultdict(int), {}, defaultdict(int)
    for k, d in cells.items():
        top = max(v["acc"] for v in d.values())
        for f, v in d.items():
            gaps[f].append(top - v["acc"])
            seen[f] += 1
            folds[f] = v["folds"]
            if v["acc"] >= top - 1e-9:
                wins[f] += 1
    for f, g in sorted(gaps.items(), key=lambda kv: np.mean(kv[1])):
        L.append(f"| `{f}` | {FAMILY_KIND.get(f, '?')} | {np.mean(g):.2f} | "
                 f"{wins[f]}/{seen[f]} | {'yes' if folds[f] else 'no'} | {seen[f]} |")
    L.append("")

    # ---- srGW hyper-parameters -------------------------------------------
    sr = [r for r in rows if r["encoder_family"].startswith("srgw")]
    if sr:
        L += ["## srGW-MDS hyper-parameters", "",
              "Best accuracy reached at each setting (across all models and `r`).", ""]
        for field, title in (("lam", "λ (reconstruction weight)"),
                             ("landmark_strategy", "landmark strategy"),
                             ("K", "number of landmarks K"),
                             ("out_of_sample_method", "out-of-sample extension")):
            d = defaultdict(float)
            for r in sr:
                d[r[field]] = max(d[r[field]], r["acc"])
            L += [f"**{title}**", "", "| setting | best acc |", "|---|---|"]
            L += [f"| {k} | {v:.2f}% |" for k, v in sorted(d.items(), key=lambda kv: -kv[1])]
            L.append("")

    # ---- accuracy vs r ----------------------------------------------------
    L += ["## Accuracy vs. input budget", "",
          "Best encoder at each GRIDE multiplier, per model.", ""]
    for tag, rs in sorted(by_model.items()):
        per_r = {}
        for r in rs:
            if r["r"] not in per_r or r["acc"] > per_r[r["r"]]["acc"]:
                per_r[r["r"]] = r
        b = best_per_model[tag]
        L += [f"**`{tag}`** — D={b['input_dim']}, d_input={b['d_in']:.2f}, "
              f"dense {b['dense']:.2f}%, hidden-only {b['hidden']:.2f}%", "",
              "| r | mult | best acc | Δ dense | in window | encoder |", "|---|---|---|---|---|---|"]
        for rr in sorted(per_r):
            v = per_r[rr]
            L.append(f"| {rr} | ×{rr/v['d_in']:.2f} | {v['acc']:.2f}% | "
                     f"{v['acc']-v['dense']:+.2f} | {'YES' if v['hit'] else 'no'} | "
                     f"`{v['encoder_family']}` |")
        L.append("")

    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(rows)} runs, {len(by_model)} models, {n_hit} in window)")


if __name__ == "__main__":
    main()
