#!/usr/bin/env python3
"""Emit LaTeX for the follow-up results, straight into the paper's tables/ dir.

The paper's own rule is that a quoted number must be regenerated from disk by a
code path different from the one that wrote it. These experiments produce their
own CSVs, so the same rule applies: this script reads those CSVs and writes
`tables/table8_seeds.tex` and `tables/table9_thinet.tex`, the extra baseline
rows the paper `\\input`s.

    python3 make_paper_tables.py
"""

from __future__ import annotations

import csv
import statistics as st
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
TAB = HERE / "tables"
TAB.mkdir(parents=True, exist_ok=True)


def read(name):
    p = RES / name
    if not p.exists():
        return None
    with p.open() as fh:
        rows = list(csv.DictReader(fh))
    return rows or None


def paired(rows, a, b):
    cells = defaultdict(dict)
    for r in rows:
        cells[(r["model"], r["multiplier"])][r["strategy"]] = float(r["acc"])
    d = [c[a] - c[b] for c in cells.values() if a in c and b in c]
    if not d:
        return None
    n = len(d)
    m = sum(d) / n
    s = (sum((x - m) ** 2 for x in d) / n) ** 0.5
    se = s / n ** 0.5 if n > 1 else float("nan")
    return {"mean": m, "se": se, "t": m / se if se else float("nan"),
            "wins": sum(x > 0 for x in d), "n": n}


# ---------------------------------------------------------------------------

def table_thinet():
    rows = read("e3_thinet.csv")
    if not rows:
        print("skip table9: no e3 data")
        return
    order = [
        ("S4_omp_ls", r"\textbf{Ours}: $U^{\!\top}\!Y$ selection $+$ refit"),
        ("T2_thinet_lsfull", r"\quad ThiNet selection, our refit"),
        ("S3_span_ls", r"\quad span selection, our refit"),
        ("S2_magnitude_ls", r"\quad magnitude selection, our refit"),
        ("T3_thinet_densetgt", r"\quad ThiNet $+$ dense target, its rescale"),
        ("T1_thinet", r"\textsc{ThiNet} as published"),
    ]
    lines = []
    for s, lab, fam in (
            ("T1_thinet", r"\textsc{ThiNet} \cite{luo2017thinet}", "sel.$+$scale"),
            ("T3_thinet_densetgt", r"\quad $+$ dense target", "sel.$+$scale"),
            ("T2_thinet_lsfull", r"\quad $+$ our refit instead", "sel.$+$fit")):
        st_ = paired(rows, s, "S4_omp_ls")
        if not st_:
            continue
        lines.append(f"{lab} & {fam} & ${st_['mean']:+.2f}$ & "
                     f"{st_['wins']}/{st_['n']} \\\\")

    t1 = paired(rows, "T1_thinet", "S4_omp_ls")
    t3 = paired(rows, "T3_thinet_densetgt", "T1_thinet")
    t2 = paired(rows, "T2_thinet_lsfull", "T1_thinet")
    rest = t1["mean"] - t3["mean"] - t2["mean"] if (t1 and t2 and t3) else None

    body = r"""% Generated by to_do_experiment/make_paper_tables.py from e3_thinet.csv.
% Extra rows for the baselines table: ThiNet as published, plus the two
% single-difference variants. Same 16 paired cells as each other, a different
% (smaller) set than the 50-cell tournament, which the caption states.
\midrule
\multicolumn{4}{l}{\emph{\textsc{ThiNet} as published, 16 paired cells}} \\
""" + "\n".join(lines) + r"""
"""
    (TAB / "table9_thinet.tex").write_text(body + "\n")
    print("wrote table9_thinet.tex")


def table_seeds():
    rows = read("e1_seed_variance.csv")
    rb = read("e1b_robust_frontier.csv")
    if not rows:
        print("skip table8: no e1 data")
        return
    by = defaultdict(list)
    for r in rows:
        by[r["model"]].append(r)
    sds = {m: (st.stdev([float(r["acc"]) for r in rs]) if len(rs) > 1 else 0.0)
           for m, rs in by.items()}
    tot = sum(len(rs) for rs in by.values())
    inw = sum(1 for r in rows if abs(float(r["drop"])) <= 2.5)
    nseeds = len({r["seed"] for r in rows})

    costs = []
    if rb:
        costs = [float(r["cost_pts"]) for r in rb if r["cost_pts"] != ""]

    body = r"""\begin{table}[t]
\centering
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lr}
\toprule
Quantity & value \\
\midrule
Median accuracy s.d.\ over """ + f"{nseeds}" + r""" seeds & """ + \
        f"{st.median(list(sds.values())):.2f}" + r""" pts \\
Maximum accuracy s.d. & """ + f"{max(sds.values()):.2f}" + r""" pts \\
Runs still inside the $\pm2.5$ window & """ + f"{inw}/{tot}" + r""" \\
Models whose widths are seed-stable & """ + \
        f"{sum(1 for rs in by.values() if len({r['widths'] for r in rs}) == 1)}/{len(by)}" + r""" \\
\midrule
""" + (r"""Cost of a $2\sigma$-robust frontier (median) & """ +
       f"{st.median(costs):.1f}" + r""" pp \\
\quad range over models & """ + f"{min(costs):.1f}--{max(costs):.1f}" + r""" pp \\"""
       if costs else "") + r"""
\bottomrule
\end{tabular}
\caption{\textbf{Seed sensitivity.} Each saved frontier configuration re-run at
""" + f"{nseeds}" + r""" calibration seeds. Accuracy at a \emph{fixed}
configuration is stable, but a frontier is by construction the tightest budget
still inside the window --- a boundary point --- so a fraction of re-draws fall
outside it, and the measured intrinsic dimensions move enough to change
$\mathrm{round}(\alpha d_l)$ on every model. Requiring a $2\sigma$ margin
restores the guarantee for a median cost of about a percentage point of
compression.}
\label{tab:seeds}
\end{table}"""
    (TAB / "table8_seeds.tex").write_text(body + "\n")
    print("wrote table8_seeds.tex")


if __name__ == "__main__":
    table_seeds()
    table_thinet()
